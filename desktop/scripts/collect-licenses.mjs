#!/usr/bin/env node
// Assembles a single combined third-party license document from every
// wheel actually vendored for a given platform/arch - this is what
// electron-builder's nsis.license shows as the Windows installer's license
// page, and what scripts/build-mac-pkg.mjs wires into the macOS pkg's
// Distribution.xml <license> element. Automated rather than a hand-picked
// list: it reads each wheel's own dist-info metadata/license file via
// scripts/extract_wheel_licenses.py, so it can't silently miss a
// transitive dependency and stays correct as versions/deps change.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import path from "node:path";

const LICENSE_TEXTS_DIR = path.join(import.meta.dirname, "license-texts");

// Normalizes the many ways packages spell a license in their `License:`
// field or `Classifier: License ::` metadata into one of the SPDX ids we
// keep a full text for in license-texts/. Extend this (and fetch the
// corresponding text into license-texts/) if a future dependency uses a
// license not covered here - collectLicense() below reports clearly when
// nothing matches rather than guessing.
const SPDX_ALIASES = [
  [/^mit\b/i, "MIT"],
  [/apache/i, "Apache-2.0"],
  [/bsd.*3|3.clause.*bsd/i, "BSD-3-Clause"],
  [/bsd.*2|2.clause.*bsd/i, "BSD-2-Clause"],
  [/^bsd\b/i, "BSD-3-Clause"], // ambiguous "BSD License" classifier - 3-clause is the common case
  [/mozilla public license 2|mpl.?2/i, "MPL-2.0"],
];

// Packages whose wheel carries neither a License field nor embedded license
// text (checked empirically - see scripts/collect-licenses.mjs commit
// history) but whose upstream license is well-known and was confirmed
// directly against their source repo's LICENSE file.
const KNOWN_LICENSE_OVERRIDES = {
  streamlit: "Apache-2.0",
};

function resolveSpdxId(name, licenseExpr, classifiers) {
  if (KNOWN_LICENSE_OVERRIDES[name]) return KNOWN_LICENSE_OVERRIDES[name];
  const candidates = [licenseExpr, ...classifiers].filter(Boolean);
  for (const candidate of candidates) {
    for (const [pattern, spdxId] of SPDX_ALIASES) {
      if (pattern.test(candidate)) return spdxId;
    }
  }
  return null;
}

function fallbackText(spdxId) {
  const file = path.join(LICENSE_TEXTS_DIR, `${spdxId}.txt`);
  return existsSync(file) ? readFileSync(file, "utf8") : null;
}

function parseArgs() {
  const args = process.argv.slice(2);
  const out = {};
  for (let i = 0; i < args.length; i += 2) {
    out[args[i].replace(/^--/, "")] = args[i + 1];
  }
  if (!out.platform || !out.arch) {
    throw new Error("usage: collect-licenses.mjs --platform <win32|darwin|linux> --arch <x64|arm64>");
  }
  return out;
}

function main() {
  const { platform, arch } = parseArgs();
  const wheelDir = path.join("resources", "wheels", `${platform}-${arch}`);
  if (!existsSync(wheelDir)) {
    throw new Error(`${wheelDir} doesn't exist - run fetch:wheels for this platform/arch first`);
  }

  const raw = execFileSync("python3", [
    path.join(import.meta.dirname, "extract_wheel_licenses.py"),
    wheelDir,
  ]);
  const packages = JSON.parse(raw.toString());

  let embedded = 0;
  let fallback = 0;
  let missing = [];

  const sections = packages
    .filter((p) => p.name)
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((p) => {
      const declared = p.license_expr || (p.classifiers.length ? p.classifiers.join(", ") : "unknown");
      let text = p.license_text;
      let note = "";

      if (text) {
        embedded += 1;
      } else {
        const spdxId = resolveSpdxId(p.name, p.license_expr, p.classifiers);
        text = spdxId ? fallbackText(spdxId) : null;
        if (text) {
          fallback += 1;
          note = `(standard ${spdxId} license text - not embedded in this package's own distribution)\n\n`;
        } else {
          missing.push(p.name);
          text = `License text not available for this package. Declared license: ${declared}.\nSee https://pypi.org/project/${p.name}/ for details.`;
        }
      }

      return (
        `${"=".repeat(80)}\n` +
        `${p.name} ${p.version}\n` +
        `Declared license: ${declared}\n` +
        `${"=".repeat(80)}\n` +
        note +
        text
      );
    });

  const header =
    `Third-party licenses for PyADI-JIF\n` +
    `Generated by scripts/collect-licenses.mjs from ${packages.length} vendored packages ` +
    `(${platform}-${arch}). This includes pyadi-jif itself (EPL-2.0) and everything it pulls\n` +
    `in - see each section below for the specific license governing that package.\n\n`;

  // Written directly into build/ (electron-builder's buildResourcesDir) as
  // a bare "license.txt" rather than a nested path. A user report said the
  // NSIS license page wasn't appearing when this lived at
  // build/generated/THIRD-PARTY-LICENSES.txt; that path went through a
  // resolve-with-fallback branch in electron-builder's license resolution
  // (packager.getResource), vs. the direct buildResourcesDir-file-list
  // match this bare-filename form takes - the latter is the documented,
  // default-detection convention every electron-builder project relying on
  // this feature exercises, so it's the safer bet even though the exact
  // failure mode in the nested-path case wasn't confirmed with certainty
  // (NSIS compresses the license page's own data, so static inspection of
  // the built .exe can't directly confirm either version one way or the
  // other - this needs an actual Windows run to fully verify).
  const outDir = "build";
  mkdirSync(outDir, { recursive: true });
  const outPath = path.join(outDir, "license.txt");
  writeFileSync(outPath, header + sections.join("\n\n"));

  console.log(
    `Wrote ${outPath}: ${packages.length} packages (${embedded} embedded license text, ` +
      `${fallback} using standard SPDX fallback text, ${missing.length} with no text found)`
  );
  if (missing.length > 0) {
    console.log(`No license text found for: ${missing.join(", ")} - review manually.`);
  }
}

main();
